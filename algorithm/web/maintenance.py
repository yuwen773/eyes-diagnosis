"""Generate a local maintenance gateway; never start/reload a proxy or touch a DB.

Keep the output directory and ledger across the entire first cutover. Opening
Python writes is a durable, conservative boundary even before config activation.
After that boundary only Python repair/redeployment is permitted.
"""

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import re
from typing import Any

from web.cutover import ROOT


def render(*, route: str, policy: str, ports: tuple[int, int, int], runtime: Path) -> str:
    if len(set(ports)) != 3 or any(not 1 <= port <= 65535 for port in ports):
        raise ValueError("Require three distinct valid loopback ports")

    def quoted(path: Path) -> str:
        value = path.resolve().as_posix()
        if any(char in value for char in ('"', '$', '\n', '\r')):
            raise ValueError("Unsupported Nginx path character")
        return '"' + value + '"'

    # These POST routes only query state or change login sessions. No prefix
    # matches: future routes fail closed until explicitly classified.
    reads = ["user/login", "user/logout", "diagnosis/list/page/my", "diagnosis/list/page/vo",
             "diagnosis/list/page/vo/cache", "news/list/page/vo", "news/list/page/vo/cache",
             "knowledge/list/page", "user/list/page/vo", "user/list/page/vo/cache"]
    allowed = '\n'.join(f'        "POST:/api/{path}" 0;' for path in reads)
    guard = 'if ($maintenance_write) { return 503; }' if policy == "readonly" else ""
    return f'''# Generated by web.maintenance: {route}/{policy}; loopback rehearsal only
worker_processes 1;
pid {quoted(runtime / 'nginx.pid')};
error_log {quoted(runtime / 'error.log')};
events {{ worker_connections 1024; }}
http {{
    access_log off;
    map_hash_bucket_size 128;
    client_body_temp_path {quoted(runtime / 'client_temp')};
    proxy_temp_path {quoted(runtime / 'proxy_temp')};
    map "$request_method:$uri" $maintenance_write {{
        default 1;
        ~^(GET|HEAD|OPTIONS): 0;
{allowed}
    }}
    server {{
        listen 127.0.0.1:{ports[0]};
        server_name localhost;
        client_max_body_size 20m;
        error_page 503 = @paused;
        location @paused {{
            default_type application/json;
            add_header Retry-After 60 always;
            return 503 '{{"code":50300,"data":null,"msg":"Maintenance: writes paused"}}';
        }}
        location /api/ {{
            {guard}
            proxy_pass http://127.0.0.1:{ports[1] if route == 'legacy' else ports[2]};
            include {quoted(ROOT / 'deploy/snippets/eye-proxy-headers.conf')};
            proxy_buffering off;
            proxy_read_timeout 120s;
        }}
        location = /health {{ return 200 'gateway'; }}
        location / {{ return 404; }}
    }}
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--route", choices=["legacy", "python"], required=True)
    parser.add_argument("--policy", choices=["readonly", "active"], required=True)
    for name in ("listen", "legacy", "python"):
        parser.add_argument(f"--{name}-port", type=int, required=True)
    parser.add_argument("--release", required=True, help="Full immutable Git commit")
    parser.add_argument("--artifact-sha256", required=True)
    parser.add_argument("--reason", required=True)
    args = parser.parse_args()
    if args.output.name.lower() in {"maintenance.json", "maintenance.lock"}:
        parser.error("Output must not replace the maintenance ledger or lock")
    runtime = args.output.resolve().parent
    runtime.mkdir(parents=True, exist_ok=True)
    lock = runtime / "maintenance.lock"
    acquired = False
    try:
        # The lock fails closed after a crash. An operator must inspect the
        # ledger and installed configuration before removing an abandoned lock.
        with lock.open("x"):
            acquired = True
            ledger_path = runtime / "maintenance.json"
            ledger: dict[str, Any] = json.loads(ledger_path.read_text()) if ledger_path.exists() else {
                "pythonWritesOpened": False, "transitions": []}
            if ledger["pythonWritesOpened"] and args.route == "legacy":
                raise ValueError("Python writes opened: stop writes and use Python forward repair; legacy rollback forbidden")
            if not re.fullmatch(r"[0-9a-f]{40}", args.release) or not re.fullmatch(r"[0-9a-f]{64}", args.artifact_sha256):
                raise ValueError("Require full release commit and artifact SHA256")
            content = render(route=args.route, policy=args.policy,
                             ports=(args.listen_port, args.legacy_port, args.python_port), runtime=runtime)
            for name in ("client_temp", "proxy_temp", "logs", "temp"):
                (runtime / name).mkdir(exist_ok=True)
            ledger["pythonWritesOpened"] |= args.route == "python" and args.policy == "active"
            ledger["transitions"].append({"route": args.route, "policy": args.policy,
                "release": args.release, "artifactSha256": args.artifact_sha256,
                "reason": args.reason, "atUtc": datetime.now(timezone.utc).isoformat()})
            # Write the boundary before emitting an active config. Failure can
            # restrict rollback unnecessarily, but cannot permit unsafe rollback.
            temporary = ledger_path.with_suffix(".tmp")
            temporary.write_text(json.dumps(ledger, indent=2) + '\n', encoding="utf-8")
            temporary.replace(ledger_path)
            temporary = args.output.with_suffix(".tmp")
            temporary.write_text(content, encoding="utf-8")
            temporary.replace(args.output)
    except FileExistsError:
        parser.error("Maintenance generator locked; inspect prior operation before retry")
    except (ValueError, KeyError) as error:
        parser.error(str(error))
    finally:
        # Never remove another invocation's lock.
        if acquired:
            lock.unlink()


if __name__ == "__main__":
    main()
