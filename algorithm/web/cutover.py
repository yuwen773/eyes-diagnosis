"""Render a standalone Nginx configuration; never reload or deploy it implicitly.

This reproduces the **ticket-20 maintenance-window rehearsal** (the
``/api/diagnosis/workflows`` durable-upload cutover), not ticket 02's. Ticket 02
changed what the rendered config should say about session paths -- they are no
longer pinned to Java -- but it added no new rehearsal of its own: the
acceptance criteria for moving the session authority are exercised by
``web/verify_session_identity.py`` against real MySQL/Redis, while this module
still exists so the older rehearsal keeps reproducing exactly as it did.
"""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def render(*, business: str, agent: str, workflows: str, listen_port: int,
           java_port: int, python_port: int, frontend: Path, runtime: Path) -> str:
    ports = (listen_port, java_port, python_port)
    if len(set(ports)) != 3 or any(not 1 <= port <= 65535 for port in ports):
        raise ValueError("Listener, Java and Python require three distinct valid ports")
    if workflows == "active" and (business != "python" or agent != "python"):
        raise ValueError("Active admissions require both routes on Python; use drain/pause during rollback")

    def quoted(path: Path) -> str:
        value = path.resolve().as_posix()
        if any(char in value for char in ('"', '$', '\n', '\r')):
            raise ValueError("Unsupported Nginx path character")
        return '"' + value + '"'

    headers = quoted(ROOT / "deploy/snippets/eye-proxy-headers.conf")
    readonly = 'if ($request_method !~ ^(GET|HEAD|OPTIONS)$) { return 503; }'
    pause = readonly if workflows == "pause" else ""
    locations = []

    def location(pattern: str, backend: str, guard: str = "", *, stream: bool = False,
                 suffix: str = "") -> None:
        locations.append(f"""    location {pattern} {{
        {guard}
        proxy_pass http://eye_{backend}{suffix};
        include {headers};
        {('proxy_buffering off; proxy_cache off; gzip off; proxy_read_timeout 3600s;') if stream else ''}
    }}""")

    # Session paths used to be pinned to Java by exact-match locations, because
    # Spring Session's Redis payload was unreadable from Python. Python owns the
    # session namespace now (ticket 02), so they are not special-cased at all:
    # they ride whatever `business` is set to. During a rollback -- business=java
    # -- that means they go back to Java alongside every other user endpoint,
    # which is what a pre-Python-slot deployment expects.
    # New graph tasks are never handed to a legacy Java executor.
    location("= /api/diagnosis/workflows", "python",
             'if ($request_method = POST) { return 503; }' if workflows != "active" else "")
    location("^~ /api/diagnosis/workflows/", "python", pause, stream=True)
    for path in ("/api/reviews/tasks", "/api/reviews/tasks/"):
        location(("= " if not path.endswith("/") else "^~ ") + path, "python", pause)
    # Retain a same-origin recovery namespace after the normal Agent route rolls back.
    # /api cookie Path still applies. No new chat or attachment mutation is admitted.
    location("^~ /api/python-recovery/chat/", "python", "return 503;")
    location("^~ /api/python-recovery/image/", "python", "return 503;")
    for path in ("supplements/", "tool-confirmations/"):
        location("^~ /api/python-recovery/" + path, "python", pause, suffix="/api/agent/" + path)
    location("/api/python-recovery/", "python", readonly, suffix="/api/agent/", stream=True)
    stream_guard = "return 503;" if agent == "python" and workflows != "active" else ""
    location("/api/agent/chat/stream", agent, stream_guard, stream=True)
    # Pending Python supplement/tool approvals must never be sent to Java.
    for path in ("supplements/", "tool-confirmations", "tool-confirmations/"):
        location(("^~ " if path.endswith("/") else "= ") + "/api/agent/" + path, "python", pause)
    location("/api/agent/", agent, readonly if agent == "python" and workflows != "active" else "")
    location("/api/", business)
    location("= /health", "python")
    return f"""# Generated by python -m web.cutover; policy={workflows} business={business} agent={agent}
worker_processes 1;
pid {quoted(runtime / 'nginx.pid')};
error_log {quoted(runtime / 'error.log')};
events {{ worker_connections 1024; }}
http {{
    include {quoted(ROOT / 'deploy/mime.types')};
    default_type application/octet-stream;
    access_log off;
    client_body_temp_path {quoted(runtime / 'client_temp')};
    proxy_temp_path {quoted(runtime / 'proxy_temp')};
    upstream eye_java {{ server 127.0.0.1:{java_port}; }}
    upstream eye_python {{ server 127.0.0.1:{python_port}; }}
    server {{
        listen 127.0.0.1:{listen_port};
        server_name localhost;
        client_max_body_size 10m;
        proxy_connect_timeout 10s;
        proxy_read_timeout 60s;
        error_page 503 = @paused;
        location @paused {{
            default_type application/json;
            add_header Retry-After 60 always;
            return 503 '{{"code":50300,"data":null,"msg":"Migration paused; retry after recovery"}}';
        }}
{chr(10).join(locations)}
        location / {{
            root {quoted(frontend)};
            try_files $uri $uri/ /index.html;
        }}
    }}
}}
"""


def main() -> None:
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--business", choices=("java", "python"), default="python")
    parser.add_argument("--agent", choices=("java", "python"), default="python")
    parser.add_argument("--workflows", choices=("active", "drain", "pause"), default="active")
    parser.add_argument("--listen-port", type=int, default=8081)
    parser.add_argument("--java-port", type=int, default=8082)
    parser.add_argument("--python-port", type=int, default=8080)
    parser.add_argument("--frontend", type=Path, default=ROOT / "frontend/dist")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        content = render(business=args.business, agent=args.agent, workflows=args.workflows,
            listen_port=args.listen_port, java_port=args.java_port, python_port=args.python_port,
            frontend=args.frontend, runtime=args.output.resolve().parent)
    except ValueError as exc:
        parser.error(str(exc))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    for name in ("client_temp", "proxy_temp", "logs", "temp"):
        (args.output.parent / name).mkdir(exist_ok=True)
    args.output.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
