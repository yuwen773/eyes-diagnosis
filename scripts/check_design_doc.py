#!/usr/bin/env python3
"""Deterministic structural gate for the Java multi-agent design document.

The v3 revision was driven by 22 subagents repeatedly running `grep -c` for
anchors, table rows, and Mermaid fences. Those are mechanical checks and
belong in one script; reviewers should spend their attention on judgement
calls (three recovery mechanisms, the 14+3=17 table count, terminology
boundaries) that no grep can decide.

The contract records exact counts for required phrases, forbidden phrases,
section numbering, table row counts, and fence pairing. Regenerate it with
`--update` when the document is intentionally revised.

Usage:
    python3 scripts/check_design_doc.py                 # verify
    python3 scripts/check_design_doc.py --update       # regenerate contract
    python3 scripts/check_design_doc.py <doc> <contract.json>
"""

import argparse
import json
import re
import sys
from pathlib import Path

DOC = Path("docs/plans/2026-11-04-java-multi-agent-architecture-design.md")
CONTRACT = Path("docs/plans/design-doc-contract.json")

# Phrases that must appear exactly once. `None` means "at least once" and is
# used only where the phrase is legitimately referenced from several sections.
REQUIRED = {
    "v3 修订候选稿": 1,
    "基于状态图的多阶段医疗 AI 工作流架构": 1,
    "三种不同机制": 1,
    "14 张核心业务表": 1,
    "citationSetDigest": 5,
    "不是已获临床验证的黄金标准": 2,
    "四类人工交互按各自机制跨重启恢复": 1,
    "不保证全过程 exactly-once": 1,
    "RedisSaver 仅用于图引擎技术验证": 1,
}

# v2/v3 rewrites left stale phrasing behind. Each of these must be gone.
FORBIDDEN = [
    "四态状态机",
    "node 身份落 subType",
    "借 `t_agent_message.subType` 存",
    "citationDigest",
    "15 节点",
    "8 类",
]


def measure(path):
    text = path.read_text(encoding="utf-8")
    return {
        "required": {phrase: text.count(phrase) for phrase in REQUIRED},
        "forbidden": {phrase: text.count(phrase) for phrase in FORBIDDEN},
        "sections": re.findall(r"^## (\d+)\.", text, re.M),
        "fences": sum(1 for line in text.splitlines() if line.strip().startswith("```")),
        "p_rows": len(re.findall(r"^\| \*\*P[0-6]", text, re.M)),
        "r_nums": re.findall(r"^\| (R[0-9]+) \|", text, re.M),
    }


def build_contract(facts):
    return {
        "_note": "Generated by scripts/check_design_doc.py --update. Exact counts are the contract.",
        "required": facts["required"],
        "forbidden": {phrase: 0 for phrase in facts["forbidden"]},
        "sections": facts["sections"],
        "fences": facts["fences"],
        "p_rows": facts["p_rows"],
        "r_nums": facts["r_nums"],
    }


def check(facts, contract):
    errors = []
    for phrase, expected in contract["required"].items():
        actual = facts["required"].get(phrase, 0)
        if actual != expected:
            errors.append(f"required phrase {phrase!r}: expected {expected}, found {actual}")
    for phrase, expected in contract["forbidden"].items():
        actual = facts["forbidden"].get(phrase, 0)
        if actual != expected:
            errors.append(f"forbidden phrase {phrase!r}: expected {expected}, found {actual}")
    if facts["sections"] != contract["sections"]:
        errors.append(f"sections: expected {contract['sections']}, found {facts['sections']}")
    if facts["fences"] != contract["fences"] or facts["fences"] % 2:
        errors.append(f"fences: expected {contract['fences']} (even), found {facts['fences']}")
    if facts["p_rows"] != contract["p_rows"]:
        errors.append(f"P0-P6 rows: expected {contract['p_rows']}, found {facts['p_rows']}")
    expected_r = [f"R{i}" for i in range(1, len(contract["r_nums"]) + 1)]
    if facts["r_nums"] != expected_r or facts["r_nums"] != contract["r_nums"]:
        errors.append(f"risk rows: expected contiguous {expected_r}, found {facts['r_nums']}")
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("doc", nargs="?", type=Path, default=DOC)
    parser.add_argument("contract", nargs="?", type=Path, default=CONTRACT)
    parser.add_argument("--update", action="store_true")
    args = parser.parse_args()

    if not args.doc.is_file():
        print(f"design doc gate failed: {args.doc} does not exist", file=sys.stderr)
        return 2
    facts = measure(args.doc)
    if args.update:
        args.contract.parent.mkdir(parents=True, exist_ok=True)
        with open(args.contract, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(json.dumps(build_contract(facts), ensure_ascii=False, indent=2) + "\n")
        print(f"wrote {args.contract} from {args.doc}")
        return 0
    try:
        contract = json.loads(args.contract.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"design doc gate failed: cannot read contract: {exc}", file=sys.stderr)
        return 2
    errors = check(facts, contract)
    if errors:
        for error in errors:
            print(f"design doc gate failed: {error}", file=sys.stderr)
        return 1
    print(
        f"design doc gate passed: {len(REQUIRED)} anchors, "
        f"{len(FORBIDDEN)} forbidden phrases, {facts['p_rows']} stage rows, "
        f"{len(facts['r_nums'])} risk rows, {facts['fences']} fences"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
