CREATE TABLE t_workflow_job (
    jobId VARCHAR(64) NOT NULL,
    workflowId VARCHAR(64) NOT NULL,
    jobType VARCHAR(32) NOT NULL,
    segmentCode VARCHAR(64) NOT NULL,
    executionEpoch BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL,
    attempt INT NOT NULL DEFAULT 0,
    maxAttempts INT NOT NULL,
    availableAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    leaseOwner VARCHAR(128),
    leaseToken VARCHAR(128),
    leaseVersion BIGINT NOT NULL DEFAULT 0,
    leaseUntil DATETIME(6),
    graphThreadId VARCHAR(128),
    graphCheckpointId VARCHAR(128),
    lastErrorCode VARCHAR(64),
    createdAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (jobId),
    CONSTRAINT uk_workflow_job_business UNIQUE (workflowId, executionEpoch, segmentCode, jobType),
    INDEX idx_workflow_job_ready (status, availableAt, jobId),
    INDEX idx_workflow_job_workflow_status (workflowId, status),
    INDEX idx_workflow_job_lease_status (leaseUntil, status),
    INDEX idx_workflow_job_epoch (workflowId, executionEpoch)
) COMMENT 'One job per Graph-native segment execution';

CREATE TABLE t_workflow_node_execution (
    nodeExecutionId VARCHAR(64) NOT NULL,
    workflowId VARCHAR(64) NOT NULL,
    executionEpoch BIGINT NOT NULL,
    segmentCode VARCHAR(64) NOT NULL,
    nodeCode VARCHAR(96) NOT NULL,
    idempotencyKey VARCHAR(160) NOT NULL,
    status VARCHAR(32) NOT NULL,
    inputDigest VARCHAR(128),
    outputDigest VARCHAR(128),
    resultReference VARCHAR(256),
    errorCode VARCHAR(64),
    startedAt DATETIME(6),
    completedAt DATETIME(6),
    createdAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (nodeExecutionId),
    CONSTRAINT uk_node_execution_idempotency UNIQUE (idempotencyKey),
    INDEX idx_node_execution_workflow_epoch (workflowId, executionEpoch)
) COMMENT 'Idempotent node execution record';

CREATE TABLE t_inference_envelope (
    inferenceEnvelopeId VARCHAR(64) NOT NULL,
    workflowId VARCHAR(64) NOT NULL,
    inferenceEpoch BIGINT NOT NULL,
    imageObjectReference VARCHAR(512) NOT NULL,
    inputDigest VARCHAR(128) NOT NULL,
    detectedMediaType VARCHAR(128),
    qualityOutcome VARCHAR(32) NOT NULL,
    qualityScore INT NOT NULL,
    qualityReasonCodesSnapshot TEXT,
    inferenceOutcomeType VARCHAR(32) NOT NULL,
    predictionSnapshot TEXT,
    confidenceSnapshot TEXT,
    safetyAbstentionReasonCode VARCHAR(64),
    technicalFailureCode VARCHAR(64),
    oodSnapshot TEXT,
    calibrationSnapshot TEXT,
    modelVersion VARCHAR(128) NOT NULL,
    modelWeightFingerprint VARCHAR(128) NOT NULL,
    preprocessVersion VARCHAR(128),
    inferencePolicyVersion VARCHAR(128),
    inferredAt DATETIME(6) NOT NULL,
    createdAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (inferenceEnvelopeId),
    CONSTRAINT uk_inference_envelope_epoch UNIQUE (workflowId, inferenceEpoch)
) COMMENT 'Immutable logical inference epoch snapshot';
