CREATE TABLE t_diagnosis_workflow (
    workflowId VARCHAR(64) NOT NULL,
    ownerUserId BIGINT NOT NULL,
    creationIdempotencyKey VARCHAR(128) NOT NULL,
    status VARCHAR(48) NOT NULL,
    currentSegmentCode VARCHAR(64),
    graphDefinitionVersion VARCHAR(64) NOT NULL,
    graphDefinitionHash VARCHAR(128) NOT NULL,
    actionVersion VARCHAR(64) NOT NULL,
    workflowVersion BIGINT NOT NULL DEFAULT 0,
    inferenceEpoch BIGINT NOT NULL DEFAULT 0,
    inferenceEnvelopeId VARCHAR(64),
    explanationPublicationStatus VARCHAR(32) NOT NULL,
    predictionExposureStatus VARCHAR(48) NOT NULL,
    stopReasonCode VARCHAR(64),
    limitationReasonCode VARCHAR(64),
    questionText TEXT,
    createdAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (workflowId),
    CONSTRAINT uk_workflow_owner_idempotency UNIQUE (ownerUserId, creationIdempotencyKey),
    CONSTRAINT ck_workflow_version_nonnegative CHECK (workflowVersion >= 0),
    CONSTRAINT ck_workflow_inference_epoch_nonnegative CHECK (inferenceEpoch >= 0),
    INDEX idx_workflow_owner_created (ownerUserId, createdAt),
    INDEX idx_workflow_status_updated (status, updatedAt),
    INDEX idx_workflow_graph_status (graphDefinitionVersion, status)
) COMMENT 'Workflow aggregate and audit root';

CREATE TABLE t_diagnosis_workflow_event (
    eventId VARCHAR(64) NOT NULL,
    workflowId VARCHAR(64) NOT NULL,
    eventSequence BIGINT NOT NULL,
    eventType VARCHAR(64) NOT NULL,
    actorType VARCHAR(32) NOT NULL,
    actorId VARCHAR(64),
    workflowVersion BIGINT NOT NULL,
    segmentCode VARCHAR(64),
    reasonCode VARCHAR(64),
    payloadSnapshot TEXT,
    occurredAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (eventId),
    CONSTRAINT uk_workflow_event_sequence UNIQUE (workflowId, eventSequence),
    INDEX idx_workflow_event_timeline (workflowId, occurredAt)
) COMMENT 'Append-only workflow audit timeline';
